/** Etiqueta exacta de la lista (sin importar mayúsculas/acentos) o null. */
export function buscarSector(texto) {
  const n = norm(texto);
  return SECTORES.find((s) => norm(s.etiqueta) === n) || null;
}

export function norm(t) {
  return String(t || '').normalize('NFD').replace(/[\u0300-\u036f]/g, '').toLowerCase().trim();
}
